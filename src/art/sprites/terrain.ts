/**
 * The ground, one tile a sprite, each written in the steps of a single
 * terrain ramp so the setting it is laid in decides its colours: the same
 * grass is sunlit on the beach, heavy in the fen and mossy underground.
 *
 * Every tile repeats with no seam, and where two kinds of ground meet an edge
 * is composed over both (`art/ground.ts`). Written in digits, one per step,
 * since a single ramp needs no letters.
 */
function steps(ramp: TerrainRampId, keys: string): Record<string, ColourRef> {
  return Object.fromEntries([...keys].map((step) => [step, `${ramp}.${step}` as ColourRef]));
}

function tile(
  id: string,
  ramp: TerrainRampId,
  keys: string,
  animations: SpriteDef['animations'],
): SpriteDef {
  return {
    id,
    kind: 'tile',
    width: TILE_PIXELS,
    height: TILE_PIXELS,
    legend: steps(ramp, keys),
    animations,
  };
}

