/**
 * The moments drawn over the world (B5): a hit landing, a crit, a level
 * gained, a fireball and a knife in flight; and the sack a kill leaves when the
 * pack is full, which stands on the ground like any prop.
 *
 * An effect is light, and light has no edge, so the compiler outlines none of
 * these but the sack: each fades out through its own ramp to its darkest step
 * instead. Each plays its budget's four frames once; how long the view holds
 * the last one and fades it is the view's, as a corpse lies after its fall.
 * What an arrow and a telegraph are drawn as is not here: an arrow is a line at
 * whatever angle it flies, and a telegraph a ring at whatever reach its ability
 * has, which no fixed frame can be (`render2d/effects.ts`).
 */

