import { layoutZone } from './zoneText';

/**
 * Old Mill Road (decision 120, `docs/lore/places.md`): the road west out of
 * Lampton, gone to seed, on the rows the high street leaves by, so walking out
 * of one and into the other reads as one road rather than two zones that
 * happen to touch. It runs as far as the mill yard and stops; the road north to
 * Greyford is the way on.
 *
 * The millpond is in the north-west, filled by the stream that comes down past
 * Greyford, and the mill stands on its bank with its back to the water. Under
 * the pond is the shrine the first charter dammed it over, seen from the bank
 * between two of the willows round it. The pond is in the corner furthest from
 * where a traveller arrives: water is a wall you can see over, and a wall
 * between the road and the fighting would make the zone read as two rooms.
 *
 * The north edge is Greyford's south edge, the stream and all, so it leaves only
 * east of the stream (a mouth, decision 119), and an arrival lands in the same
 * stretch; the east edge is Lampton's west, whole. Nothing that can see a
 * traveller stands within its reach of either.
 */
