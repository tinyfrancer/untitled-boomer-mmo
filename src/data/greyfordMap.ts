/**
 * Greyford Outpost (decision 120, `docs/lore/places.md`): the Company's forward
 * post at a ford of grey stones, where a stream comes down off the Greyhills'
 * west end. It joins the Old Mill Road to the New Cut, so the way home from the
 * hardwood is not the way you came, and there is nothing to fight here, which is
 * what makes it somewhere to stand.
 *
 * The road from the New Cut comes in along the east edge's middle rows and runs
 * the length of the yard to the ford; the road south to the mill road leaves it
 * halfway. The counters front the road from its north side as Lampton's do,
 * the trading post and the fettler's longhouse, and the fettler's store stands
 * against the back of the longhouse with its door round the back, where nobody
 * in the yard sees it. The tannery and the fletcher's bench are at the yard's
 * west end, by the water. The outpost's people live in the cottages.
 *
 * The ford is the fallen bridge: its abutments either side of the water, two of
 * its piers still standing in the stream, and its stones the dressed stone the
 * piers came down as, the keystone among them. Over it the old road goes on a
 * little way west and is grown over: the Stillwood is that way.
 *
 * The stream runs off the south edge into the Old Mill Road's millpond, so the
 * way south is the edge east of it, and the mill road's north edge is the same
 * stretch: a mouth (decision 119), the first outdoors. The east edge is the New
 * Cut's ledge the whole way down, and nothing stands on it.
 */
